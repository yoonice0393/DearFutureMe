-- DearFutureMe schema.
-- Letter content (subject + body) is AES-256-GCM encrypted by Edge Functions
-- before it reaches the database; only ciphertext is stored here.

create extension if not exists pgcrypto with schema extensions;

create type public.letter_status as enum (
  'draft', 'pending_verification', 'sealed', 'sending', 'delivered', 'failed', 'cancelled'
);
create type public.letter_source as enum ('booth', 'event_phone', 'web');

-- ── profiles ────────────────────────────────────────────────────────────────
create table public.profiles (
  id              uuid primary key references auth.users (id) on delete cascade,
  email           text not null,
  consent_version text,
  consent_at      timestamptz,
  unsubscribed    boolean not null default false,
  role            text not null default 'user' check (role in ('user', 'admin')),
  created_at      timestamptz not null default now()
);

-- ── events ──────────────────────────────────────────────────────────────────
create table public.events (
  id              uuid primary key default gen_random_uuid(),
  name            text not null check (char_length(name) between 1 and 120),
  slug            text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{2,39}$'),
  starts_at       timestamptz not null,
  ends_at         timestamptz not null,
  submission_cap  integer not null default 300 check (submission_cap > 0),
  static_code_cap integer not null default 100 check (static_code_cap >= 0),
  staff_pin_hash  text not null,              -- bcrypt via pgcrypto crypt()
  paused          boolean not null default false,
  allowed_presets integer[] not null default '{6,12,24,36,60,120}',
  created_at      timestamptz not null default now(),
  check (ends_at > starts_at)
);

-- ── kiosks (registered booth devices) ───────────────────────────────────────
create table public.kiosks (
  id          uuid primary key default gen_random_uuid(),
  event_id    uuid not null references public.events (id) on delete cascade,
  label       text check (char_length(label) <= 60),
  token_hash  text not null unique,           -- sha256 hex of the random token
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  revoked_at  timestamptz
);
create index kiosks_event_idx on public.kiosks (event_id);

-- ── letters ─────────────────────────────────────────────────────────────────
create table public.letters (
  id               uuid primary key,          -- generated by the Edge Function (bound into the AES-GCM AAD)
  user_id          uuid references auth.users (id) on delete cascade,
  recipient_email  text,
  email_hash       text,                      -- HMAC-SHA256(lower(email)); for limits without scanning plaintext
  kiosk_id         uuid references public.kiosks (id) on delete set null,
  event_id         uuid references public.events (id) on delete set null,
  source           public.letter_source not null,
  via_static_code  boolean not null default false,  -- event_phone via the printed QR (own lower cap)
  body_ciphertext  bytea not null,            -- encrypted JSON {subject, body}
  body_iv          bytea not null,
  key_version      smallint not null default 1,
  deliver_at       timestamptz,
  timezone         text check (char_length(timezone) <= 64),
  status           public.letter_status not null default 'draft',
  is_sealed        boolean not null default false,   -- "can't read until delivery" (v2)
  mood_tag         text check (char_length(mood_tag) <= 32),
  attempts         integer not null default 0,
  next_attempt_at  timestamptz,
  last_error       text check (char_length(last_error) <= 500),
  consent_version  text,
  consent_at       timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  delivered_at     timestamptz,
  cancelled_at     timestamptz,
  -- Anything past draft must have somewhere and some time to go.
  check (status = 'draft' or (recipient_email is not null and email_hash is not null and deliver_at is not null)),
  check (status = 'draft' or consent_at is not null)
);

create index letters_due_idx      on public.letters (status, deliver_at);
create index letters_user_idx     on public.letters (user_id);
create index letters_kiosk_idx    on public.letters (kiosk_id);
create index letters_event_idx    on public.letters (event_id);
create index letters_active_email on public.letters (email_hash)
  where status in ('pending_verification', 'sealed', 'sending');

create function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create trigger letters_touch before update on public.letters
  for each row execute function public.touch_updated_at();

-- ── email verification (web flow without sign-in) ──────────────────────────
create table public.email_verifications (
  token_hash  text primary key,               -- sha256 hex
  email_hash  text not null,
  letter_id   uuid not null references public.letters (id) on delete cascade,
  expires_at  timestamptz not null,
  used_at     timestamptz,
  created_at  timestamptz not null default now()
);
create index email_verifications_letter_idx on public.email_verifications (letter_id);

-- ── delivery log (never contains letter content) ────────────────────────────
create table public.send_log (
  id                  bigint generated always as identity primary key,
  letter_id           uuid references public.letters (id) on delete set null,
  kind                text not null check (kind in ('receipt', 'verify', 'letter', 'reminder')),
  attempt             integer not null default 1,
  provider            text,
  provider_message_id text,
  status              text not null,
  error               text check (char_length(error) <= 500),
  created_at          timestamptz not null default now()
);
create index send_log_letter_idx on public.send_log (letter_id);

-- ── suppression ("This wasn't me", unsubscribe, bounces) ────────────────────
create table public.suppressed_emails (
  email_hash  text primary key,
  reason      text not null check (reason in ('not_me', 'unsubscribe', 'bounce', 'complaint')),
  created_at  timestamptz not null default now()
);

-- ── rate limiting (sliding windows) ─────────────────────────────────────────
create table public.rate_events (
  id         bigint generated always as identity primary key,
  scope      text not null,                   -- 'kiosk' | 'event' | 'ip' | 'user' | 'pin' | 'email'
  key_hash   text not null,
  created_at timestamptz not null default now()
);
create index rate_events_lookup on public.rate_events (scope, key_hash, created_at);
