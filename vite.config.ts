import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import react from "@vitejs/plugin-react";
import { defineConfig, loadEnv, type Plugin } from "vite";

/**
 * 1. Start the app's JavaScript just after the first paint. The home page is
 *    prerendered into index.html (scripts/prerender.mjs), so on slow phones
 *    people see it while React downloads, instead of a blank page.
 * 2. Security headers: Cloudflare Pages' `dist/_headers`, with a strict CSP
 *    that names the real Supabase origin and allows our one inline script by
 *    its SHA-256 hash (no 'unsafe-inline'). `vite preview` serves the same file.
 */
function deferredBootAndHeaders(env: Record<string, string>): Plugin {
  const themeScript = readFileSync(new URL("./src/theme-init.js", import.meta.url), "utf8").trim();
  const supabase = env.VITE_SUPABASE_URL ? new URL(env.VITE_SUPABASE_URL).origin : "";
  const turnstile = "https://challenges.cloudflare.com";
  let outDir = "dist";
  let isSsr = false;

  function headersFile(scriptHashes: string[]): string {
    const csp = [
      "default-src 'self'",
      `script-src 'self' ${scriptHashes.map((h) => `'sha256-${h}'`).join(" ")} ${turnstile}`,
      "style-src 'self'",
      "style-src-attr 'unsafe-inline'", // React style={{…}} attributes only; no <style> injection
      "img-src 'self' data: blob:",
      "font-src 'self'",
      `connect-src 'self' ${supabase}`.trim(),
      `frame-src ${turnstile}`,
      "worker-src 'self' blob:",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "frame-ancestors 'none'",
      "upgrade-insecure-requests",
    ].join("; ");
    const common = {
      "Content-Security-Policy": csp,
      "X-Content-Type-Options": "nosniff",
      "Referrer-Policy": "strict-origin-when-cross-origin",
      "Permissions-Policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()",
      "Strict-Transport-Security": "max-age=63072000; includeSubDomains",
      "X-Frame-Options": "DENY",
      "Cross-Origin-Opener-Policy": "same-origin",
    };
    // Shared booth devices: never keep these pages in the back/forward cache.
    const noStore = { "Cache-Control": "no-store" };
    const rules: [string, Record<string, string>][] = [
      ["/*", common],
      ["/booth", noStore],
      ["/booth/*", noStore],
      ["/e/*", noStore],
      ["/manage/*", noStore],
      ["/verify", noStore],
      ["/assets/*", { "Cache-Control": "public, max-age=31536000, immutable" }],
    ];
    const body = rules
      .map(([path, h]) => `${path}\n${Object.entries(h).map(([k, v]) => `  ${k}: ${v}`).join("\n")}`)
      .join("\n\n");
    return `# Generated by vite.config.ts. Do not edit.\n${body}\n`;
  }

  /** Minimal parser for our own _headers format (used by `vite preview`). */
  function parseHeaders(text: string): [string, [string, string][]][] {
    const rules: [string, [string, string][]][] = [];
    for (const line of text.split("\n")) {
      if (!line.trim() || line.startsWith("#")) continue;
      if (!line.startsWith(" ")) rules.push([line.trim(), []]);
      else {
        const i = line.indexOf(":");
        rules[rules.length - 1][1].push([line.slice(0, i).trim(), line.slice(i + 1).trim()]);
      }
    }
    return rules;
  }

  return {
    name: "dfm-deferred-boot-and-headers",
    configResolved(c) {
      outDir = resolve(c.root, c.build.outDir);
      isSsr = !!c.build.ssr;
    },
    transformIndexHtml: {
      order: "post",
      handler(html) {
        // Dev server: keep Vite's normal module loading, just inline the theme script.
        const main = /<script type="module" crossorigin src="([^"]+)"><\/script>\s*/.exec(html);
        if (!main) {
          return html.replace('<script src="/theme-init.js"></script>', `<script>${themeScript}</script>`);
        }
        const loader =
          `(function(){var s=document.createElement("script");s.type="module";s.src=${JSON.stringify(main[1])};` +
          `var d=0,go=function(){if(!d++)document.head.appendChild(s)};` +
          `requestAnimationFrame(function(){setTimeout(go,0)});setTimeout(go,500)})()`;
        return html
          .replace(main[0], "")
          .replace(/<link rel="modulepreload"[^>]*>\s*/g, "")
          .replace('<script src="/theme-init.js"></script>', `<script>${themeScript};${loader}</script>`);
      },
    },
    writeBundle() {
      if (isSsr) return;
      const html = readFileSync(resolve(outDir, "index.html"), "utf8");
      const hashes = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) =>
        createHash("sha256").update(m[1]).digest("base64"),
      );
      writeFileSync(resolve(outDir, "_headers"), headersFile(hashes));
    },
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => {
        const file = resolve(outDir, "_headers");
        if (existsSync(file)) {
          const url = req.url ?? "/";
          for (const [path, headers] of parseHeaders(readFileSync(file, "utf8"))) {
            const match = path === "/*" || url === path || (path.endsWith("/*") && url.startsWith(path.slice(0, -1)));
            if (match) for (const [k, v] of headers) res.setHeader(k, v);
          }
        }
        next();
      });
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), "VITE_");
  return {
    plugins: [react(), deferredBootAndHeaders(env)],
    resolve: {
      alias: { "@shared": "/supabase/functions/_shared", "@": "/src" },
    },
    build: {
      sourcemap: false,
    },
  };
});
